# 2. Function to load and merge all 5 years
def load_and_merge_data(folder_path):
    data_frames = []
    # Files are usually named 1year.arff, 2year.arff, etc.
    for i in range(1, 6):
        file_name = f"{i}year.arff"
        file_path = os.path.join(folder_path, file_name)
        if os.path.exists(file_path):
            data, meta = arff.loadarff(file_path)
            temp_df = pd.DataFrame(data)
            data_frames.append(temp_df)
            print(f"Loaded: {file_name}")

    combined_df = pd.concat(data_frames, ignore_index=True)
    # Decode target class from bytes to int (0 or 1)
    combined_df['class'] = combined_df['class'].str.decode('utf-8').astype(int)
    return combined_df

# Execute loading from the extracted folder
